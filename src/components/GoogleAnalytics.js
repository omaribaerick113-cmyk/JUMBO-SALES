import Script from 'next/script';

/**
 * Loads Google Analytics (GA4) only if NEXT_PUBLIC_GA_MEASUREMENT_ID is set in
 * Vercel's environment variables. Safe to deploy without it configured yet —
 * simply renders nothing until you add your real Measurement ID.
 */
export default function GoogleAnalytics() {
  const gaId = process.env.NEXT_PUBLIC_GA_MEASUREMENT_ID;
  if (!gaId) return null;

  return (
    <>
      <Script
        src={`https://www.googletagmanager.com/gtag/js?id=${gaId}`}
        strategy="afterInteractive"
      />
      <Script id="google-analytics" strategy="afterInteractive">
        {`
          window.dataLayer = window.dataLayer || [];
          function gtag(){dataLayer.push(arguments);}
          gtag('js', new Date());
          gtag('config', '${gaId}');
        `}
      </Script>
    </>
  );
}
